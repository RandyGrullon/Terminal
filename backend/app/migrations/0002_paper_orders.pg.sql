-- 0002 · Pending entry orders of the demo account (limit / stop). Mirrors 0002_paper_orders.sqlite.sql.
-- Time columns: *_time = unix seconds; *_at = unix milliseconds (BIGINT).
CREATE TABLE IF NOT EXISTS paper_orders (
  id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  account_id   BIGINT NOT NULL,
  symbol       TEXT NOT NULL,
  tf           TEXT,
  side         TEXT NOT NULL,
  kind         TEXT NOT NULL,
  price        DOUBLE PRECISION NOT NULL,
  qty          DOUBLE PRECISION,
  risk_pct     DOUBLE PRECISION,
  sl           DOUBLE PRECISION,
  tp           DOUBLE PRECISION,
  expiry       TEXT NOT NULL DEFAULT 'gtc',
  expire_bars  BIGINT,
  expire_time  BIGINT,
  status       TEXT NOT NULL DEFAULT 'pending',
  origin       TEXT NOT NULL DEFAULT 'manual',
  gate_verdict TEXT,
  gate_score   DOUBLE PRECISION,
  position_id  BIGINT,
  fill_price   DOUBLE PRECISION,
  fill_time    BIGINT,
  reason       TEXT,
  cancelled_by TEXT,
  created_at   BIGINT NOT NULL,
  updated_at   BIGINT NOT NULL,
  meta         TEXT
);
CREATE INDEX IF NOT EXISTS idx_orders_status ON paper_orders (account_id, status);
