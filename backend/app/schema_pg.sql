-- NEXUS Terminal database for PostgreSQL / Supabase (cloud mode). Mirrors app/schema.sql.
-- BASELINE (schema version 1, frozen): later changes are numbered migrations in app/migrations/ (one .sqlite.sql and
-- one .pg.sql file each), applied in order by init_schema and recorded in schema_migrations(version, name, applied_at).
-- Tables live in their own schema ("{schema}", default "nexus") so Supabase's public Data API never exposes them,
-- and RLS is enabled without policies as defense in depth (the backend connects as the table owner).
-- Time columns: `time`/`*_time` = unix seconds; `ts`/`*_at` = unix milliseconds (BIGINT).

CREATE SCHEMA IF NOT EXISTS {schema};
SET search_path TO {schema};

CREATE TABLE IF NOT EXISTS meta (
  key   TEXT PRIMARY KEY,
  value TEXT
);

CREATE TABLE IF NOT EXISTS settings (
  key        TEXT PRIMARY KEY,
  value      TEXT NOT NULL,
  updated_at BIGINT NOT NULL
);

CREATE TABLE IF NOT EXISTS symbols (
  symbol      TEXT PRIMARY KEY,
  ticker      TEXT,
  exchange    TEXT,
  description TEXT,
  type        TEXT,
  market      TEXT,
  currency    TEXT,
  pricescale  BIGINT,
  logoid      TEXT,
  provider    TEXT,
  history     TEXT,
  updated_at  BIGINT
);

CREATE TABLE IF NOT EXISTS candles (
  symbol TEXT NOT NULL,
  tf     TEXT NOT NULL,
  time   BIGINT NOT NULL,
  open   DOUBLE PRECISION NOT NULL,
  high   DOUBLE PRECISION NOT NULL,
  low    DOUBLE PRECISION NOT NULL,
  close  DOUBLE PRECISION NOT NULL,
  volume DOUBLE PRECISION NOT NULL DEFAULT 0,
  source TEXT,
  PRIMARY KEY (symbol, tf, time)
);

CREATE TABLE IF NOT EXISTS watchlist (
  symbol   TEXT PRIMARY KEY,
  position BIGINT NOT NULL DEFAULT 0,
  added_at BIGINT NOT NULL
);

CREATE TABLE IF NOT EXISTS model_state (
  kind          TEXT NOT NULL,         -- nexus | scanner | gate | nexus_veto
  key           TEXT NOT NULL,         -- "SYMBOL|tf" | "market|tf|horizon" | "global"
  state         TEXT NOT NULL,
  updates       BIGINT NOT NULL DEFAULT 0,
  trained_until BIGINT,
  updated_at    BIGINT NOT NULL,
  PRIMARY KEY (kind, key)
);
-- kind='nexus_veto' (key "SYMBOL|tf"): entries the market-conditions semáforo vetoed; the engine rejects them on
-- later runs. state = {version, entries:[{time, direction, level, detail, at}]} (newest 200 kept).

CREATE TABLE IF NOT EXISTS signals (
  id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  symbol     TEXT NOT NULL,
  tf         TEXT NOT NULL,
  time       BIGINT NOT NULL,
  action     TEXT NOT NULL,
  score      DOUBLE PRECISION,
  prob_up    DOUBLE PRECISION,
  confidence DOUBLE PRECISION,
  price      DOUBLE PRECISION,
  sl         DOUBLE PRECISION,
  tp1        DOUBLE PRECISION,
  tp2        DOUBLE PRECISION,
  tp3        DOUBLE PRECISION,
  regime     TEXT,
  verdict    TEXT,
  gate_score DOUBLE PRECISION,
  reason     TEXT,
  created_at BIGINT NOT NULL,
  UNIQUE (symbol, tf, time, action)
);
CREATE INDEX IF NOT EXISTS idx_signals_sym ON signals (symbol, tf, time);

CREATE TABLE IF NOT EXISTS predictions (
  id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  source             TEXT NOT NULL,
  symbol             TEXT NOT NULL,
  tf                 TEXT NOT NULL,
  model_key          TEXT,
  created_at         BIGINT NOT NULL,
  target_at          BIGINT NOT NULL,
  price              DOUBLE PRECISION NOT NULL,
  direction          BIGINT NOT NULL DEFAULT 0,
  prob_up            DOUBLE PRECISION NOT NULL,
  score              DOUBLE PRECISION NOT NULL DEFAULT 0,
  features           TEXT,
  resolved           BIGINT NOT NULL DEFAULT 0,
  outcome_price      DOUBLE PRECISION,
  outcome_return_pct DOUBLE PRECISION,
  correct            BIGINT,
  resolved_at        BIGINT
);
CREATE INDEX IF NOT EXISTS idx_pred_due ON predictions (resolved, target_at);
CREATE INDEX IF NOT EXISTS idx_pred_sym ON predictions (symbol, created_at);
CREATE INDEX IF NOT EXISTS idx_pred_source ON predictions (source, resolved, target_at);
CREATE INDEX IF NOT EXISTS idx_pred_model ON predictions (model_key, resolved, target_at);

-- Daily aggregates of resolved predictions (mirrors schema.sql), written in the same transaction that resolves each
-- row. Totals, hit rates, Brier and calibration read them, so they survive the pruning of old prediction rows.
-- day = UTC day of target_at (unix s); model_key = scanner "market|tf|horizon_s" | NEXUS "SYMBOL|tf"; bin = prob_up
-- calibration bin 0..9. n counts resolved rows (with or without verdict); scored/correct/up/prob_sum/brier_sum count
-- only rows with a verdict.
CREATE TABLE IF NOT EXISTS prediction_daily (
  day       BIGINT NOT NULL,
  source    TEXT NOT NULL,
  model_key TEXT NOT NULL,
  bin       BIGINT NOT NULL,
  n         BIGINT NOT NULL DEFAULT 0,
  scored    BIGINT NOT NULL DEFAULT 0,
  correct   BIGINT NOT NULL DEFAULT 0,
  up        BIGINT NOT NULL DEFAULT 0,
  prob_sum  DOUBLE PRECISION NOT NULL DEFAULT 0,
  brier_sum DOUBLE PRECISION NOT NULL DEFAULT 0,
  PRIMARY KEY (day, source, model_key, bin)
);

CREATE TABLE IF NOT EXISTS gate_log (
  id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  symbol      TEXT NOT NULL,
  tf          TEXT NOT NULL,
  time        BIGINT NOT NULL,
  direction   TEXT NOT NULL,
  verdict     TEXT NOT NULL,
  score       DOUBLE PRECISION NOT NULL,
  win_prob    DOUBLE PRECISION,
  entry       DOUBLE PRECISION,
  sl          DOUBLE PRECISION,
  tp1         DOUBLE PRECISION,
  tp2         DOUBLE PRECISION,
  checks      TEXT,
  taken       BIGINT NOT NULL DEFAULT 0,
  source      TEXT,
  created_at  BIGINT NOT NULL,
  target_at   BIGINT,
  resolved    BIGINT NOT NULL DEFAULT 0,
  outcome     TEXT,
  outcome_r   DOUBLE PRECISION,
  resolved_at BIGINT,
  UNIQUE (symbol, tf, time, direction, source)
);
CREATE INDEX IF NOT EXISTS idx_gate_due ON gate_log (resolved, target_at);

CREATE TABLE IF NOT EXISTS scan_runs (
  id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  market      TEXT NOT NULL,
  tf          TEXT NOT NULL,
  started_at  BIGINT NOT NULL,
  finished_at BIGINT,
  n_symbols   BIGINT NOT NULL DEFAULT 0,
  status      TEXT NOT NULL DEFAULT 'running',
  deep        BIGINT NOT NULL DEFAULT 0,
  message     TEXT,
  params      TEXT
);

CREATE TABLE IF NOT EXISTS scan_results (
  run_id     BIGINT NOT NULL,
  symbol     TEXT NOT NULL,
  rank       BIGINT NOT NULL,
  score      DOUBLE PRECISION,
  prob_up    DOUBLE PRECISION,
  action     TEXT,
  confidence DOUBLE PRECISION,
  price      DOUBLE PRECISION,
  change_pct DOUBLE PRECISION,
  volume     DOUBLE PRECISION,
  verdict    TEXT,
  gate_score DOUBLE PRECISION,
  data       TEXT,
  PRIMARY KEY (run_id, symbol)
);

CREATE TABLE IF NOT EXISTS paper_accounts (
  id              BIGINT PRIMARY KEY,
  name            TEXT NOT NULL,
  balance         DOUBLE PRECISION NOT NULL,
  initial_balance DOUBLE PRECISION NOT NULL,
  currency        TEXT NOT NULL DEFAULT 'USD',
  created_at      BIGINT NOT NULL,
  updated_at      BIGINT
);

CREATE TABLE IF NOT EXISTS paper_positions (
  id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  account_id   BIGINT NOT NULL,
  symbol       TEXT NOT NULL,
  tf           TEXT,
  side         TEXT NOT NULL,
  qty          DOUBLE PRECISION NOT NULL,
  qty_open     DOUBLE PRECISION NOT NULL,
  entry_price  DOUBLE PRECISION NOT NULL,
  entry_time   BIGINT NOT NULL,
  sl           DOUBLE PRECISION,
  tp1          DOUBLE PRECISION,
  tp2          DOUBLE PRECISION,
  tp3          DOUBLE PRECISION,
  trail        DOUBLE PRECISION,
  tp_hits      BIGINT NOT NULL DEFAULT 0,
  status       TEXT NOT NULL DEFAULT 'open',
  exit_price   DOUBLE PRECISION,
  exit_time    BIGINT,
  pnl          DOUBLE PRECISION NOT NULL DEFAULT 0,
  pnl_pct      DOUBLE PRECISION NOT NULL DEFAULT 0,
  r_multiple   DOUBLE PRECISION,
  exit_reason  TEXT,
  origin       TEXT NOT NULL DEFAULT 'manual',
  gate_verdict TEXT,
  gate_score   DOUBLE PRECISION,
  meta         TEXT
);
CREATE INDEX IF NOT EXISTS idx_pos_status ON paper_positions (account_id, status);

CREATE TABLE IF NOT EXISTS paper_fills (
  id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  position_id BIGINT NOT NULL,
  account_id  BIGINT NOT NULL,
  time        BIGINT NOT NULL,
  side        TEXT NOT NULL,
  qty         DOUBLE PRECISION NOT NULL,
  price       DOUBLE PRECISION NOT NULL,
  fee         DOUBLE PRECISION NOT NULL DEFAULT 0,
  reason      TEXT
);

CREATE TABLE IF NOT EXISTS events (
  id      BIGINT PRIMARY KEY,
  ts      BIGINT NOT NULL,
  level   TEXT NOT NULL,
  source  TEXT NOT NULL,
  message TEXT NOT NULL,
  data    TEXT
);
CREATE INDEX IF NOT EXISTS idx_events_ts ON events (ts);

CREATE TABLE IF NOT EXISTS scripts (
  id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name        TEXT NOT NULL UNIQUE,
  description TEXT NOT NULL DEFAULT '',
  code        TEXT NOT NULL,
  is_example  BIGINT NOT NULL DEFAULT 0,
  created_at  BIGINT NOT NULL,
  updated_at  BIGINT NOT NULL
);

CREATE TABLE IF NOT EXISTS backtests (
  id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  symbol     TEXT NOT NULL,
  tf         TEXT NOT NULL,
  params     TEXT,
  metrics    TEXT,
  created_at BIGINT NOT NULL
);

-- Row level security: app/migrations/pg_rls.sql enables RLS (no policies) on every table of the schema after the
-- baseline and the migrations, at every start (idempotent and lock-free once every table has it).
